
public class Motocicletas extends Vehiculo{
    private boolean esElectrica;
    private int cantidaCambios;
    private String tipoMoto;

    public boolean getEsElectrica() {
        return esElectrica;
    }

    public void setEsElectrica(boolean esElectrica) {
        this.esElectrica = esElectrica;
    }

    public int getCantidaCambios() {
        return cantidaCambios;
    }

    public void setCantidaCambios(int cantidaCambios) {
        this.cantidaCambios = cantidaCambios;
    }

    public String getTipoMoto() {
        return tipoMoto;
    }

    public void setTipoMoto(String tipoMoto) {
        this.tipoMoto = tipoMoto;
    }
    
    
    
}
